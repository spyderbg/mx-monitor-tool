import { writeFile } from 'node:fs/promises';
import { APP_ID, DEFAULT_BACKEND_PORT } from '../shared/config.js';

// Compose has no TS imports: generate its literals from the canonical shared config.
const content = `# Generated by npm run docker:config. Do not edit identity/port literals here.
services:
  app:
    container_name: ${APP_ID}-app
    image: ${APP_ID}
    restart: unless-stopped
    build:
      context: ..
      dockerfile: docker/app.Dockerfile
      args:
        BACKEND_PORT: "${DEFAULT_BACKEND_PORT}"
    ports:
      - "127.0.0.1:\${APP_PORT:-${DEFAULT_BACKEND_PORT}}:${DEFAULT_BACKEND_PORT}"
    environment:
      PORT: "${DEFAULT_BACKEND_PORT}"
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:' + process.env.PORT + '/api/health').then(r => process.exit(r.ok ? 0 : 1)).catch(() => process.exit(1))"]
      interval: 30s
      timeout: 3s
      retries: 3
      start_period: 5s
`;
await writeFile('docker/docker-compose.yml', content);
